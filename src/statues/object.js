import { box, cyl, lines, segs, boundsOf, scalePrims } from '../shapes/ir.js';

const OBJECTS = {
  urn: () => [
    cyl(0.25, 0.25, 0.1, [0, 0.05, 0], [0, 0, 0], 12, 'foot'), cyl(0.25, 0.45, 0.5, [0, 0.35, 0], [0, 0, 0], 12, 'belly'),
    cyl(0.45, 0.2, 0.5, [0, 0.85, 0], [0, 0, 0], 12, 'shoulder'), cyl(0.2, 0.25, 0.2, [0, 1.2, 0], [0, 0, 0], 12, 'neck'),
    cyl(0.25, 0.3, 0.05, [0, 1.325, 0], [0, 0, 0], 12, 'lip'),
  ],
  boat: () => [
    box([0.9, 0.45, 2.6], [0, 0.225, 0], [0, 0, 0], 'hull'), box([0.9, 0.06, 0.2], [0, 0.42, 0.3], [0, 0, 0], 'thwart'),
    lines([[0, 0, -1.3], [0, 0.45, -1.7], [0, 0.45, -1.3]], 'bow'), lines([[0, 0, 1.3], [0, 0.45, 1.6], [0, 0.45, 1.3]], 'stern'),
  ],
  ladder: () => {
    const p = [cyl(0.04, 0.04, 2.6, [-0.25, 1.3, 0], [0, 0, 0], 6, 'rail'), cyl(0.04, 0.04, 2.6, [0.25, 1.3, 0], [0, 0, 0], 6, 'rail')];
    for (let y = 0.3; y < 2.6; y += 0.4) p.push(box([0.5, 0.04, 0.04], [0, y, 0], [0, 0, 0], 'rung'));
    return p;
  },
  bell: () => [
    box([0.1, 1.4, 0.1], [-0.6, 0.7, 0], [0, 0, 0], 'post'), box([0.1, 1.4, 0.1], [0.6, 0.7, 0], [0, 0, 0], 'post'),
    box([1.3, 0.1, 0.12], [0, 1.45, 0], [0, 0, 0], 'yoke'), cyl(0.5, 0.3, 0.7, [0, 0.95, 0], [0, 0, 0], 16, 'bell'),
    cyl(0.12, 0.12, 0.1, [0, 1.35, 0], [0, 0, 0], 8, 'crown'), cyl(0.03, 0.05, 0.5, [0, 0.75, 0], [0, 0, 0], 6, 'clapper'),
  ],
  wheel: () => {
    const p = [box([0.9, 0.3, 0.4], [0, 0.15, 0], [0, 0, 0], 'block'), cyl(0.6, 0.6, 0.08, [0, 0.9, 0], [Math.PI / 2, 0, 0], 24, 'rim'), cyl(0.08, 0.08, 0.12, [0, 0.9, 0], [Math.PI / 2, 0, 0], 8, 'hub')];
    for (let k = 0; k < 6; k++) p.push(box([0.04, 1.1, 0.04], [0, 0.9, 0], [0, 0, k * Math.PI / 6], 'spoke'));
    return p;
  },
  loom: () => {
    const p = [];
    for (const [x, z] of [[-0.6, -0.3], [0.6, -0.3], [-0.6, 0.3], [0.6, 0.3]]) p.push(box([0.08, 1.6, 0.08], [x, 0.8, z], [0, 0, 0], 'post'));
    p.push(box([1.3, 0.08, 0.08], [0, 1.56, -0.3], [0, 0, 0], 'beam'), box([1.3, 0.08, 0.08], [0, 0.3, -0.3], [0, 0, 0], 'beam'));
    const warp = [];
    for (let x = -0.5; x <= 0.5 + 1e-9; x += 0.1) warp.push([x, 1.52, -0.3], [x, 0.34, -0.3]);
    p.push(segs(warp, 'warp'));
    return p;
  },
};

export function object(subject, scale = 1) {
  const prims = scalePrims(OBJECTS[subject](), scale);
  return { prims, boxes: [boundsOf(prims)] };
}
